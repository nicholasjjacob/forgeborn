// Extracts the game-icons.net icons the UI uses (CC BY 3.0, via @iconify-json/game-icons) into
// src/ui/iconData.ts, so only these few ship instead of the whole 4,000-icon set.
// Run: node scripts/build-icons.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const set = JSON.parse(readFileSync(require.resolve('@iconify-json/game-icons/icons.json'), 'utf8'));

const NAMES = [
  // side buttons and top bar
  'treasure-map', 'checklist', 'present', 'spell-book', 'knapsack', 'cog',
  // upgrades and perks
  'crossed-swords', 'hearts', 'sprint', 'bullseye', 'two-coins', 'broadsword', 'crystal-cluster',
  'anvil-impact', 'fast-forward-button', 'night-sleep',
  // status marks
  'padlock', 'locked-chest', 'open-chest', 'check-mark', 'position-marker', 'skull-crossed-bones', 'crown', 'compass',
  // terrains
  'grass', 'mushroom', 'cactus', 'crystal-growth', 'snowflake-1', 'volcano',
  // shop
  'hourglass', 'book-cover',
  // heroes
  'visored-helm',
];

const out = {};
for (const n of NAMES) {
  const icon = set.icons[n];
  if (!icon) throw new Error(`missing icon ${n}`);
  // Drop per-path fills so the icon takes the gradient and outline from its wrapper.
  out[n] = icon.body.replace(/\s*fill="[^"]*"/g, '');
}
writeFileSync('src/ui/iconData.ts',
  '// Generated by scripts/build-icons.mjs from game-icons.net (CC BY 3.0, https://game-icons.net). Do not edit.\n' +
  `export const ICON_DATA: Record<string, string> = ${JSON.stringify(out, null, 0).replace(/","/g, '",\n  "')};\n`);
console.log(`wrote ${NAMES.length} icons`);
